/**
 * PATCH, MINOR AND ACTIONS UPDATES FROM DEPENDABOT APPROVE AND QUEUE THEMSELVES, AND A RED `gate` IS NEVER LEFT SILENT (A11-254, under A11-251).
 *
 * Every repository with a `merge-queue-main` ruleset needs one approving review before anything merges, and nothing approved a Dependabot pull
 * request: `auto-arm.yml` had armed them all, and they sat at REVIEW_REQUIRED until a person or an agent turn dealt with them. So the template
 * for `.github/workflows/dependabot-auto.yml` is generated here, next to the one for `.github/dependabot.yml` (`dependabot-config.ts`), and
 * `dependabot-config --check` fails when either has drifted. The workflow has three jobs:
 *
 *   approve   `pull_request_target` by dependabot[bot]. Reads the update with `dependabot/fetch-metadata`; approves it as the Octo STS App only
 *             when the update is a patch or a minor (or a GitHub Actions update that is not a major) and EVERY commit on the pull request is
 *             Dependabot's; then hands the pull request to `auto-arm.yml`'s `arm-approved`, which arms it. It merges when `gate` is green.
 *   withdraw  `pull_request_target` by anyone else, on a Dependabot pull request: someone pushed to the branch, and `main` keeps stale
 *             approvals, so the approval this workflow gave is dismissed.
 *   red       `workflow_run` of `ci`, failed, for a Dependabot pull request: an infrastructure failure on attempt 1 is rerun once, anything else
 *             is commented with the failing jobs' error lines.
 *
 * THE APPROVAL IDENTITY CAN APPROVE NOTHING ELSE, BY TWO WALLS. The policy `dependabot-approve.sts.yaml` mints only for a run of `main`'s copy of
 * `dependabot-auto.yml` triggered by dependabot[bot] (its `actor_id`), so no branch's copy and no other actor can hold the token. And the
 * workflow approves only what `approve` decides. `--check` reads the policies (`verifyPolicies`) and refuses any other workflow that approves
 * (`findOtherApprovers`). The policies are hand-written, not generated, because their subject needs the repository's immutable id, which is not
 * in the tree.
 *
 * THE SCRIPTS ARE INLINE BASH AND JQ (`dependabot-auto-scripts.ts`), not a bin: a `pull_request_target` job that ran a toolchain bin would
 * install the base's dependencies with a write token in hand.
 */

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import {
  APPROVE_SCRIPT, DECIDE_SCRIPT, DEPENDABOT_LOGIN, QUEUE_SCRIPT, RED_ACT_SCRIPT, RED_READ_SCRIPT, WITHDRAW_SCRIPT,
} from "./dependabot-auto-scripts.ts";

export const DEPENDABOT_AUTO_FILE = ".github/workflows/dependabot-auto.yml";
export const APPROVE_POLICY_FILE = ".github/chainguard/dependabot-approve.sts.yaml";
export const GUARD_POLICY_FILE = ".github/chainguard/dependabot-guard.sts.yaml";
export const AUTO_ARM_FILE = ".github/workflows/auto-arm.yml";
/** dependabot[bot]'s account id, read from the `user.id` of a Dependabot pull request (a11ign/a11ign#5709). Octo STS pins the approval to it. */
export const DEPENDABOT_ACTOR_ID = "49699333";
/** The a11ign organisation's immutable id, as it appears in an OIDC `sub`. */
export const OWNER_ID = "320310787";

// Pinned by SHA, as every a11ign workflow pins an action it cannot review.
const FETCH_METADATA = "dependabot/fetch-metadata@25dd0e34f4fe68f24cc83900b1fe3fe149efef98 # v3.1.0";
const OCTO_STS = "octo-sts/action@f603d3be9d8dd9871a265776e625a27b00effe05 # v1.1.1";

const HEADER = [
  "# GENERATED by `dependabot-config --write` (@a11ign/toolchain). DO NOT EDIT BY HAND: `dependabot-config --check` fails when this file differs from its output.",
  "# A11-254: a Dependabot patch, minor or GitHub Actions update is approved and queued here, and merges when `gate` is green. A major is never approved.",
  "#",
  "# `approve` runs only for dependabot[bot], on `main`'s copy of this file (`pull_request_target`), and approves as the Octo STS App under",
  "# `.github/chainguard/dependabot-approve.sts.yaml`, whose `actor_id` is dependabot[bot]'s. It approves only when `dependabot/fetch-metadata` reads a patch, a minor",
  "# or a non-major Actions update AND every commit on the pull request is authored by dependabot[bot]. It checks out nothing: no byte of the pull request is on the runner.",
  "# `withdraw` takes the approval back when someone else pushes to the branch. `red` reruns an infrastructure failure of `ci` once and comments any other.",
  "# Both write under `.github/chainguard/dependabot-guard.sts.yaml`. Neither policy can be minted by a branch's copy of this file.",
];

const SAME_REPOSITORY = "github.event.pull_request.base.ref == 'main' && github.event.pull_request.head.repo.full_name == github.repository";
const DEPENDABOT_AUTHORED = `github.event.pull_request.user.login == '${DEPENDABOT_LOGIN}'`;

/** A `run: |` step: the script indented under the key. */
const runStep = (name: string, script: string, env: Record<string, string>, extra: { id?: string; if?: string } = {}): string[] => [
  `      - name: ${JSON.stringify(name)}`,
  ...(extra.id === undefined ? [] : [`        id: ${extra.id}`]),
  ...(extra.if === undefined ? [] : [`        if: ${extra.if}`]),
  "        env:",
  ...Object.entries(env).map(([key, value]) => `          ${key}: ${value}`),
  "        run: |",
  ...script.split("\n").map((line) => (line === "" ? "" : `          ${line}`)),
];

/** An Octo STS mint step: `identity` is the policy's file name without `.sts.yaml`. */
const mintStep = (name: string, id: string, identity: string, condition?: string): string[] => [
  `      - name: ${JSON.stringify(name)}`,
  `        id: ${id}`,
  ...(condition === undefined ? [] : [`        if: ${condition}`]),
  `        uses: ${OCTO_STS}`,
  "        with:",
  "          scope: ${{ github.repository }}",
  `          identity: ${identity}`,
];

const PR_ENV = { REPOSITORY: "${{ github.repository }}", PR_NUMBER: "${{ github.event.pull_request.number }}" };

function approveJob(): string[] {
  return [
    "  approve:",
    "    if: >-",
    `      github.event_name == 'pull_request_target' && github.actor == '${DEPENDABOT_LOGIN}'`,
    `      && ${DEPENDABOT_AUTHORED}`,
    `      && ${SAME_REPOSITORY}`,
    "    runs-on: ubuntu-latest",
    "    permissions:",
    "      contents: read",
    "      pull-requests: read",
    "      id-token: write",
    "    steps:",
    "      - name: Read the update from Dependabot's metadata",
    "        id: metadata",
    `        uses: ${FETCH_METADATA}`,
    "        with:",
    "          github-token: ${{ github.token }}",
    ...runStep("Decide: a patch, a minor or a non-major Actions update, and every commit Dependabot's", DECIDE_SCRIPT, {
      ...PR_ENV, GH_TOKEN: "${{ github.token }}", UPDATE_TYPE: "${{ steps.metadata.outputs.update-type }}", ECOSYSTEM: "${{ steps.metadata.outputs.package-ecosystem }}",
    }, { id: "decide" }),
    ...mintStep("Mint the approving token (Octo STS, `dependabot-approve.sts.yaml`): only dependabot[bot]'s run of main's copy of this file can", "approve-token", "dependabot-approve", "steps.decide.outputs.approve == 'yes'"),
    ...runStep("Approve at the commit that was read, and take it back if a commit that is not Dependabot's arrives meanwhile", APPROVE_SCRIPT, {
      ...PR_ENV, GH_TOKEN: "${{ steps.approve-token.outputs.token }}", HEAD_SHA: "${{ github.event.pull_request.head.sha }}", KIND: "${{ steps.decide.outputs.kind }}",
    }, { id: "approval", if: "steps.decide.outputs.approve == 'yes'" }),
    ...mintStep("Mint the queueing token (Octo STS, `dependabot-guard.sts.yaml`)", "guard-token", "dependabot-guard", "steps.approval.outputs.approved == 'yes'"),
    ...runStep("Hand the approved pull request to auto-arm.yml's arm-approved, which arms it for the merge queue", QUEUE_SCRIPT, {
      ...PR_ENV, GH_TOKEN: "${{ steps.guard-token.outputs.token }}",
    }, { if: "steps.approval.outputs.approved == 'yes'" }),
  ];
}

function withdrawJob(): string[] {
  return [
    "  withdraw:",
    "    if: >-",
    `      github.event_name == 'pull_request_target' && github.event.action == 'synchronize' && github.actor != '${DEPENDABOT_LOGIN}'`,
    `      && ${DEPENDABOT_AUTHORED}`,
    `      && ${SAME_REPOSITORY}`,
    "    runs-on: ubuntu-latest",
    "    permissions:",
    "      id-token: write",
    "    steps:",
    ...mintStep("Mint the withdrawing token (Octo STS, `dependabot-guard.sts.yaml`)", "guard-token", "dependabot-guard"),
    ...runStep("Dismiss this workflow's approvals when a commit on the branch is not Dependabot's", WITHDRAW_SCRIPT, {
      ...PR_ENV, GH_TOKEN: "${{ steps.guard-token.outputs.token }}",
    }),
  ];
}

/** The failed `ci` run is for a Dependabot branch's pull request run, or for a merge-queue entry (whose script finds the pull request and its author). */
const RED_CONDITION = [
  "github.event_name == 'workflow_run' && github.event.workflow_run.conclusion == 'failure'",
  "&& github.event.workflow_run.head_repository.full_name == github.repository",
  "&& ((github.event.workflow_run.event == 'pull_request' && startsWith(github.event.workflow_run.head_branch, 'dependabot/'))",
  "|| github.event.workflow_run.event == 'merge_group')",
];

function redJob(): string[] {
  const run = {
    REPOSITORY: "${{ github.repository }}", RUN_ID: "${{ github.event.workflow_run.id }}", ATTEMPT: "${{ github.event.workflow_run.run_attempt }}",
  };
  return [
    "  red:",
    "    if: >-",
    ...RED_CONDITION.map((line) => `      ${line}`),
    "    runs-on: ubuntu-latest",
    "    permissions:",
    "      actions: read",
    "      pull-requests: read",
    "      id-token: write",
    "    steps:",
    ...runStep("Read the failed run: which jobs failed, and whether it reads as infrastructure", RED_READ_SCRIPT, {
      ...run, GH_TOKEN: "${{ github.token }}", RUN_EVENT: "${{ github.event.workflow_run.event }}",
      RUN_URL: "${{ github.event.workflow_run.html_url }}", HEAD_SHA: "${{ github.event.workflow_run.head_sha }}",
      HEAD_BRANCH: "${{ github.event.workflow_run.head_branch }}", PR_FROM_EVENT: "${{ github.event.workflow_run.pull_requests[0].number }}",
    }, { id: "read" }),
    ...mintStep("Mint the rerun and comment token (Octo STS, `dependabot-guard.sts.yaml`)", "guard-token", "dependabot-guard", "steps.read.outputs.action != 'none'"),
    ...runStep("Rerun the failed jobs once, or comment the failing jobs' error lines on the pull request", RED_ACT_SCRIPT, {
      ...run, GH_TOKEN: "${{ steps.guard-token.outputs.token }}", ACTION: "${{ steps.read.outputs.action }}", PR: "${{ steps.read.outputs.pr }}", BODY: "${{ steps.read.outputs.body }}",
    }, { if: "steps.read.outputs.action != 'none'" }),
  ];
}

/** The text of `.github/workflows/dependabot-auto.yml`. The same for every repository: nothing in it names one. */
export function generateDependabotAuto(): string {
  const lines = [
    ...HEADER,
    "name: dependabot-auto",
    "",
    "on:",
    "  pull_request_target:",
    "    types: [opened, reopened, synchronize]",
    "  workflow_run:",
    "    workflows: [ci]",
    "    types: [completed]",
    "",
    "permissions: {}",
    "",
    "defaults:",
    "  run:",
    "    shell: bash",
    "",
    "jobs:",
    ...approveJob(),
    "",
    ...withdrawJob(),
    "",
    ...redJob(),
  ];
  return lines.join("\n") + "\n";
}

// ---- the policies ------------------------------------------------------------------------------------------------------------------------

export type AutoProblem = { file: string; message: string };
/** `{ path: text }` of the files `--check` reads: both policies, `auto-arm.yml` and every workflow. A path that is not there is absent. */
export type AutoFiles = Record<string, string>;

type Policy = { top: Record<string, string>; maps: Record<string, Record<string, string>> };

/** A value as YAML reads it for the shapes a policy uses: quoted (with or without a comment after it) or plain (a ` #` starts a comment). */
const unquote = (value: string): string => {
  const quoted = /^"([^"]*)"\s*(?:#.*)?$/.exec(value) ?? /^'([^']*)'\s*(?:#.*)?$/.exec(value);
  return quoted === null ? value.replace(/\s+#.*$/, "") : quoted[1];
};

/** A policy file the parser cannot read, named by line. */
class PolicyUnreadable extends Error {}

/** The policy file's shape: `key: value` at the top, and one level of `key:` then indented `key: value`. Anything else is refused by line. */
function parsePolicy(text: string): Policy {
  const policy: Policy = { top: {}, maps: {} };
  let open: string | undefined;
  for (const [index, raw] of text.split(/\r?\n/).entries()) {
    if (raw.trim() === "" || raw.trim().startsWith("#")) continue;
    const line = /^( *)([A-Za-z_][\w-]*):(?: +(.*))?$/.exec(raw);
    if (line === null || (line[1].length !== 0 && line[1].length !== 2)) throw new PolicyUnreadable(`line ${index + 1} is not \`key: value\` or an indented \`key: value\` under a key`);
    const [, indent, key, value = ""] = line;
    if (indent === "") {
      open = value === "" ? key : undefined;
      if (value === "") policy.maps[key] = {};
      else policy.top[key] = unquote(value.trim());
    } else if (open === undefined) {
      throw new PolicyUnreadable(`line ${index + 1} is indented under a key that has no map`);
    } else {
      policy.maps[open][key] = unquote(value.trim());
    }
  }
  return policy;
}

const ISSUER = "https://token.actions.githubusercontent.com";
const escapeDots = (name: string): string => name.replaceAll(".", "\\.");

type PolicyKind = {
  file: string;
  subjectKey: "subject" | "subject_pattern";
  subjectTail: string;
  eventName: string;
  claims: readonly string[];
  permissions: Record<string, string>;
};

const APPROVE: PolicyKind = {
  file: APPROVE_POLICY_FILE, subjectKey: "subject", subjectTail: ":pull_request", eventName: "pull_request_target",
  claims: ["job_workflow_ref", "event_name", "actor", "actor_id"], permissions: { pull_requests: "write" },
};
const GUARD: PolicyKind = {
  file: GUARD_POLICY_FILE, subjectKey: "subject_pattern", subjectTail: ":(pull_request|ref:refs/heads/main)", eventName: "pull_request_target|workflow_run",
  claims: ["job_workflow_ref", "event_name"], permissions: { pull_requests: "write", actions: "write" },
};

const sameEntries = (found: Record<string, string>, wanted: Record<string, string>): boolean => {
  const keys = Object.keys(found).sort();
  return keys.length === Object.keys(wanted).length && keys.every((key) => found[key] === wanted[key]);
};

/** A field that should read exactly `wanted`: no problem when it does. */
const fieldProblem = (file: string, field: string, found: string | undefined, wanted: string): AutoProblem[] =>
  found === wanted ? [] : [{ file, message: `${field} is ${found === undefined ? "missing" : JSON.stringify(found)}, expected ${JSON.stringify(wanted)}` }];

const OWNED_SUBJECT = /^repo:a11ign@(\d+)\/([\w.-]+)@(\d+)(:.*)$/;

/** The subject: which key holds it, the owner id and the tail. The repository it names is the one the claims are checked against. */
function subjectProblems(kind: PolicyKind, policy: Policy): { repo: string; problems: AutoProblem[] } {
  const { file, subjectKey } = kind;
  const other = subjectKey === "subject" ? "subject_pattern" : "subject";
  const subject = policy.top[subjectKey];
  const named = subject === undefined ? null : OWNED_SUBJECT.exec(subject);
  const misplaced = policy.top[other] === undefined ? [] : [{ file, message: `has ${other}, expected ${subjectKey}` }];
  const unknown = Object.keys(policy.top).filter((key) => ![subjectKey, "issuer", other].includes(key)).map((key) => ({ file, message: `has the key ${key}, which this policy does not take` }));
  if (named === null) {
    const shown = subject === undefined ? "missing" : JSON.stringify(subject);
    return { repo: "<repo>", problems: [...misplaced, ...unknown, { file, message: `${subjectKey} is ${shown}, expected repo:a11ign@${OWNER_ID}/<repo>@<repository id>${kind.subjectTail}` }] };
  }
  const owner = fieldProblem(file, "subject owner id", named[1], OWNER_ID);
  return { repo: named[2], problems: [...misplaced, ...unknown, ...owner, ...fieldProblem(file, `${subjectKey} tail`, named[4], kind.subjectTail)] };
}

/** The claims: main's copy of this workflow, the event, and for the approving policy dependabot[bot]'s id and login; no claim this policy does not take. */
function claimProblems(kind: PolicyKind, claims: Record<string, string>, repo: string): AutoProblem[] {
  const { file } = kind;
  const actor = kind === APPROVE
    ? [...fieldProblem(file, "claim_pattern.actor_id", claims.actor_id, DEPENDABOT_ACTOR_ID), ...fieldProblem(file, "claim_pattern.actor", claims.actor, "dependabot\\[bot\\]")]
    : [];
  const unknown = Object.keys(claims).filter((key) => !kind.claims.includes(key)).map((key) => ({ file, message: `claim_pattern has the claim ${key}, which this policy does not take` }));
  return [
    ...fieldProblem(file, "claim_pattern.job_workflow_ref", claims.job_workflow_ref, `a11ign/${escapeDots(repo)}/\\.github/workflows/dependabot-auto\\.yml@refs/heads/main`),
    ...fieldProblem(file, "claim_pattern.event_name", claims.event_name, kind.eventName),
    ...actor,
    ...unknown,
  ];
}

/** What is wrong with one policy, by field. `[]` is a policy that binds what it must. */
function policyProblems(kind: PolicyKind, text: string | undefined): AutoProblem[] {
  const { file } = kind;
  if (text === undefined) return [{ file, message: `does not exist. Write it with the repository's id (\`gh api repos/a11ign/<repo> --jq .id\`); the README's "Dependency updates" section shows it` }];
  let policy: Policy;
  try {
    policy = parsePolicy(text);
  } catch (cause) {
    if (cause instanceof PolicyUnreadable) return [{ file, message: cause.message }];
    throw cause;
  }
  const { repo, problems } = subjectProblems(kind, policy);
  const permissions = policy.maps.permissions ?? {};
  return [
    ...fieldProblem(file, "issuer", policy.top.issuer, ISSUER),
    ...problems,
    ...claimProblems(kind, policy.maps.claim_pattern ?? {}, repo),
    ...(sameEntries(permissions, kind.permissions) ? [] : [{ file, message: `permissions are ${JSON.stringify(permissions)}, expected exactly ${JSON.stringify(kind.permissions)}` }]),
  ];
}

/** The repository the two policies name must be one: a subject for one repository beside a workflow ref for another would never mint. */
function sameRepositoryProblems(files: AutoFiles): AutoProblem[] {
  const names = [APPROVE_POLICY_FILE, GUARD_POLICY_FILE].map((file) => /repo:a11ign@\d+\/([\w.-]+)@/.exec(files[file] ?? "")?.[1]);
  const [approve, guard] = names;
  return approve !== undefined && guard !== undefined && approve !== guard
    ? [{ file: GUARD_POLICY_FILE, message: `names the repository ${guard}, but ${APPROVE_POLICY_FILE} names ${approve}` }]
    : [];
}

/** What `--check` says about the two policies. */
export function verifyPolicies(files: AutoFiles): AutoProblem[] {
  return [...policyProblems(APPROVE, files[APPROVE_POLICY_FILE]), ...policyProblems(GUARD, files[GUARD_POLICY_FILE]), ...sameRepositoryProblems(files)];
}

// ---- no other workflow approves ----------------------------------------------------------------------------------------------------------

/** What approves a pull request in a workflow: the CLI flag, the API's event, or the identity itself. Comments are not read. */
const APPROVING = /--approve\b|\bAPPROVE\b|\bgh pr review\b[^\n]*\s-a\b|identity:\s*dependabot-approve\b/;
const WORKFLOW = /^\.github\/workflows\/[^/]+\.ya?ml$/;
const withoutComments = (text: string): string => text.split("\n").filter((line) => !line.trim().startsWith("#")).join("\n");

/**
 * Every workflow other than `dependabot-auto.yml` that submits an approving review, or mints the approving identity. This is the proof that the
 * identity approves nothing else: the policy lets only `dependabot-auto.yml` mint it, and no other file may even try.
 */
export function findOtherApprovers(files: AutoFiles): AutoProblem[] {
  return Object.entries(files)
    .filter(([path]) => WORKFLOW.test(path) && path !== DEPENDABOT_AUTO_FILE)
    .flatMap(([path, text]) => {
      const found = APPROVING.exec(withoutComments(text));
      return found === null ? [] : [{ file: path, message: `submits an approving review or mints the approving identity (\`${found[0]}\`). Only ${DEPENDABOT_AUTO_FILE}'s approve job may` }];
    });
}

/** `arm-approved` is what queues an approved pull request; without it the approval would leave the pull request waiting for the next sweep. */
export function armProblems(files: AutoFiles): AutoProblem[] {
  const arm = files[AUTO_ARM_FILE];
  if (arm === undefined) return [{ file: AUTO_ARM_FILE, message: "does not exist; dependabot-auto.yml hands an approved pull request to its arm-approved job" }];
  return /^ {2}arm-approved:/m.test(arm) ? [] : [{ file: AUTO_ARM_FILE, message: "has no arm-approved job, which dependabot-auto.yml hands an approved pull request to" }];
}

/** Everything `--check` reads about the approval besides the generated workflow itself. */
export function autoProblems(files: AutoFiles): AutoProblem[] {
  return [...verifyPolicies(files), ...findOtherApprovers(files), ...armProblems(files)];
}

/** The files `autoProblems` reads, from disk: the policies, `auto-arm.yml` and each workflow. */
export function readAutoFiles(root: string): AutoFiles {
  const workflows = join(root, ".github/workflows");
  const names = existsSync(workflows)
    ? readdirSync(workflows, { withFileTypes: true }).filter((entry) => entry.isFile() && /\.ya?ml$/.test(entry.name)).map((entry) => `.github/workflows/${entry.name}`)
    : [];
  const paths = [...new Set([APPROVE_POLICY_FILE, GUARD_POLICY_FILE, ...names])].filter((path) => existsSync(join(root, path)));
  return Object.fromEntries(paths.map((path) => [path, readFileSync(join(root, path), "utf8")]));
}
