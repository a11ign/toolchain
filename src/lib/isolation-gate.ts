// @ts-check
// command: prove a published package installs and works standalone, by actually installing and running it
// Can a consumer install this package and use it? Answered by doing it.
//
//   node packages/guards/src/isolation-gate.ts packages/evidence [more...]
//   npm run gate:isolation
//
// ## Why a workspace cannot answer this
//
// A workspace install resolves everything by symlink, with the repo root as the cwd, so it is
// STRUCTURALLY INCAPABLE of detecting the failures that matter to a consumer (ADR 0007):
//
// - **phantom dependencies** — npm's hoisting makes an undeclared import resolve anyway;
// - **cwd-relative resolution** — `local-judge.ts` resolved the scorer as `".venv/bin/python"` and
//   `"scripts/score-screenreader-model.py"`, which work only when the cwd is the repo root;
// - **files dropped by `"files"`** — `.ps1`, `.cmd` and `.safetensors` payloads are exactly what an
//   allow-list loses silently;
// - **`"exports"` subpaths that do not resolve** the paths the README tells people to import.
//
// So the gate packs the package, installs the tarball into a fresh directory OUTSIDE the repository, and
// runs the package's own smoke test there. Continuous Delivery's smoke-test-the-deployed-artefact
// discipline, applied to a tarball.
//
// ## Two package managers, on purpose (#2301)
//
// THE PACK HALF IS pnpm's AND THE CONSUMER HALF IS npm's. The release publishes with `pnpm publish`
// (changesets picks the tool from the workspace), so what a consumer receives is what `pnpm pack` makes:
// packing with anything else would check a tarball nobody publishes. But the person who runs
// `npm install a11ign` is not a pnpm user by assumption, so the tarballs are installed with NPM, into a
// directory that is not a workspace. A gate that installed with pnpm would prove the wrong thing: pnpm's
// stricter resolution is the point of packing with it, and the reason the install must not use it.
//
// **A THIRD CHECK LIVES BETWEEN THE TWO, and it exists because npm cannot be trusted to notice.** Every
// internal dependency in a packed `package.json` must carry a real range that the sibling being packed
// alongside actually SATISFIES, read out of the tarball and not out of the source. A `workspace:*` left in
// a tarball installs for nobody, and npm does say so. A range the sibling does NOT satisfy is worse: npm
// resolves it from the REGISTRY, silently, and a consumer of the real release would run a different copy
// of `@a11ign/evidence` than the one this gate just tested (`packedRangeProblems`).
//
// ## One trap, learned the hard way
//
// **A pack includes untracked files** (`npm pack` always did; `pnpm pack` is checked for it in
// `isolation-gate-refuses.test.ts`). A tarball built on a machine that happens to hold a missing file
// contains it, which is exactly how `scripts/score-screenreader-model.py` — the default judge backend —
// went missing from the repo for the project's whole life while every local run succeeded.
// `packedButUntracked` below now catches that class: a packed file git neither tracks nor ignores exists
// only on the machine that packed it. `src/referenced-scripts.test.ts` still covers the other half by
// asserting tracked-ness.
//
// **SCOPE — the sentence the next reader needs.** That check can only bite on a package whose `"files"`
// list ships SOURCE, and there are three: `nvda-worker` (`src`), `scorer` (`bin`, `python`,
// `models/screenreader-scorer`) and `worker-fleet` (`src/local-worker`, `src/provisioning`). The other
// three published packages ship `["dist", ...]` — gitignored build output, regenerated by `npm run build`
// — so a source file somebody forgot to commit is never packed there at all and this gate is
// structurally silent about it. That is not a gap to close: it is where the defect can happen, and it is
// where the historical one did (`python/` in `scorer`). Proved by planting a file in `evidence` and
// watching nothing fire — a bite-proof that fails usefully rather than one that flatters the guard.
